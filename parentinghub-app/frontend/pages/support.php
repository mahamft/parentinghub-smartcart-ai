function renderSupportFAQs() {
  const box = document.getElementById("faqAccordion");
  if (!box) return;
  const allFaqs = (typeof FAQS !== "undefined" && Array.isArray(FAQS)) ? FAQS : [];
  box.innerHTML = allFaqs.length ? allFaqs.map((f) => `
    <details class="panel" style="border:1px solid var(--line);border-radius:14px;padding:14px 18px;cursor:pointer">
      <summary style="font-weight:600;font-size:15px;color:var(--ink);display:flex;justify-content:space-between;align-items:center;list-style:none">
        <span>${f.q || f.question || ''}</span>
        <span style="color:var(--primary);font-size:18px;font-weight:700">+</span>
      </summary>
      <p style="margin:12px 0 0;font-size:14px;line-height:1.6;color:var(--ink-2)">${f.a || f.answer || ''}</p>
    </details>
  `).join("") : '<div class="panel"><p class="small muted">FAQs are not available yet.</p></div>';
}

async function handleSupportInquiry(e) {
  e.preventDefault();
  const name = document.getElementById("inqName").value.trim();
  const contact = document.getElementById("inqContact").value.trim();
  const topic = document.getElementById("inqTopic").value;
  const message = document.getElementById("inqMsg").value.trim();
  const btn = document.getElementById("inqBtn");

  if (!name || !contact || !message) return false;
  btn.disabled = true;
  btn.textContent = "Submitting...";

  try {
    const res = await fetch("/api/inquiries", {
      method: "POST",
      headers: { "Content-Type": "application/json", "X-Requested-With": "XMLHttpRequest" },
      body: JSON.stringify({ name, contact, topic, message, type: "support" })
    });
    const data = await res.json().catch(() => null);
    if (data && data.success) {
      document.getElementById("supportInqForm").reset();
      document.getElementById("inqSuccessMsg").style.display = "block";
      if (typeof toast === "function") toast("Inquiry received! We'll reach out shortly");
    } else {
      if (typeof toast === "function") toast(data?.message || "Failed to submit inquiry", "x");
    }
  } catch (err) {
    if (typeof toast === "function") toast("Connection issue. Please reach out by email.", "x");
  } finally {
    btn.disabled = false;
    btn.textContent = "Submit Inquiry";
  }
  return false;
}

document.addEventListener("DOMContentLoaded", renderSupportFAQs);
